#!/usr/bin/env node
// Regenerates client/packages/protocol/src/generated/packet-map.ts from an upstream
// realmlib packet-map.ts + packet-type.ts pair.
//
// Two independent upstream forks currently agree on the packet map for the live
// Exalt build:
//   - HiveManager/HeadlessClient/realmlib
//   - Nexus/headless/realmlib
//
// After a game patch, sync from either upstream (they should still match), then run:
//   node scripts/sync-packet-map.mjs <path-to-realmlib/src>
//
// The generator preserves REC's historical packet-name overrides via an aliases
// map so downstream code that references e.g. VAULT_UPDATE keeps working while
// realmlib's canonical VAULT_CONTENT is exposed as PacketAlias.VAULT_CONTENT.

import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');
const OUT_PATH = join(REPO_ROOT, 'packages', 'protocol', 'src', 'generated', 'packet-map.ts');

const upstream = process.argv[2];
if (!upstream) {
  console.error('Usage: node scripts/sync-packet-map.mjs <path-to-realmlib/src>');
  console.error('Example: node scripts/sync-packet-map.mjs ../../HiveManager/HeadlessClient/realmlib/src');
  process.exit(2);
}
const MAP_PATH = resolve(upstream, 'packet-map.ts');
const TYPE_PATH = resolve(upstream, 'packet-type.ts');

function loadHiveMap(path) {
  const m = new Map();
  const re = /^\s*(\d+):\s*PacketType\.([A-Z0-9_]+),?\s*(?:\/\/\s*(.*))?$/;
  for (const line of readFileSync(path, 'utf-8').split(/\r?\n/)) {
    const mo = re.exec(line);
    if (mo) m.set(Number(mo[1]), { name: mo[2], comment: (mo[3] ?? '').trim() });
  }
  return m;
}
function loadEnum(path) {
  const s = new Set();
  const re = /^\s*([A-Z0-9_]+)\s*=\s*['"]([A-Z0-9_]+)['"]/;
  for (const line of readFileSync(path, 'utf-8').split(/\r?\n/)) {
    const mo = re.exec(line);
    if (mo) s.add(mo[1]);
  }
  return s;
}
function loadRecDirections(text) {
  const d = new Map();
  const idx = text.indexOf('export const PACKET_DIRECTION');
  if (idx < 0) return d;
  const re = /^\s*([A-Z0-9_]+):\s*"(Incoming|Outgoing)"/;
  for (const line of text.slice(idx).split(/\r?\n/)) {
    const mo = re.exec(line);
    if (mo) d.set(mo[1], mo[2]);
  }
  return d;
}

const hiveMap = loadHiveMap(MAP_PATH);
const hiveEnum = loadEnum(TYPE_PATH);

// Historical REC name -> realmlib canonical. REC's name stays PRIMARY so downstream
// string comparisons keep working; realmlib's name is exported as an alias.
const REC_PREFERS = {
  'VAULT_CONTENT':        'VAULT_UPDATE',
  'SHOOTACK':             'SHOOT_ACK',
  'CHANGE_ALLY_SHOOT':    'CHANGE_ALLYSHOOT',
  'CLAIM_MISSION_RESULT': 'CLAIM_MISSION_RESULT', // REC previously had UNKNOWN164
  'PROGRESS_UPDATE':      'PROGRESS_UPDATE',       // REC previously had UNKNOWN165
  'ENCHANT':              'ENCHANT',                // REC previously had UNKNOWN190
};
const preferredName = (hn) => REC_PREFERS[hn] ?? hn;
const aliasPairs = Object.entries(REC_PREFERS).filter(([h, r]) => h !== r);

// Direction table: prefer prior REC value; fall back to heuristic.
let priorDirs = new Map();
try {
  const prior = readFileSync(OUT_PATH, 'utf-8');
  priorDirs = loadRecDirections(prior);
} catch {
  // No prior file; try git HEAD copy
  try {
    const priorGit = execSync(`git -C "${REPO_ROOT}/.." show HEAD:client/packages/protocol/src/generated/packet-map.ts`, { encoding: 'utf-8' });
    priorDirs = loadRecDirections(priorGit);
  } catch {}
}
function guessDir(name) {
  if (priorDirs.has(name)) return priorDirs.get(name);
  const incomingSuffixes = ['_RESULT', '_RESPONSE', '_INFO', '_MESSAGE', '_UPDATE', '_PROMPT', '_CHANGED', '_BONUS'];
  if (incomingSuffixes.some(s => name.endsWith(s))) return 'Incoming';
  const outgoingHints = ['ACK', 'CLAIM_', 'DASH', 'ENTER_', 'ACCEPT_', 'REDEEM_',
    'BLACKSMITH_', 'REROLL_', 'RESET_', 'UNLOCK_', 'UPGRADE_', 'APPLY_',
    'ACTIVATE_', 'CRUCIBLE_REQUEST', 'FORGE_REQUEST', 'SELECT_ENTRANCE',
    'BUY_', 'EDIT', 'SET_', 'CANCEL', 'REDEEM_VOUCHER', 'BOOST_'];
  if (outgoingHints.some(h => name.includes(h))) return 'Outgoing';
  return 'Incoming';
}

// Compose primary enum: preferred (REC) names ∪ any prior REC enum names ∪ Hive enum
const primary = new Set([...hiveEnum].map(preferredName));
for (const { name } of hiveMap.values()) primary.add(preferredName(name));
const primaryNames = [...primary].sort();

const lines = [];
lines.push(`import type { PacketMap } from '../packet-map.js';`);
lines.push(`import { invertPacketMap } from '../packet-map.js';`);
lines.push('');
lines.push('// AUTO-GENERATED by scripts/sync-packet-map.mjs from the canonical realmlib packet map.');
lines.push('// Upstream: HiveManager/HeadlessClient/realmlib/src/packet-map.ts +');
lines.push('//           Nexus/headless/realmlib/src/packet-map.ts (byte-identical).');
lines.push('// Two independent upstream forks agree on the mapping for the live Exalt build.');
lines.push('// To update after a game patch: re-sync from either upstream and rerun this script.');
lines.push('//');
lines.push("// A handful of packet names differ between REC's historical naming and realmlib's.");
lines.push("// The map entry uses REC's name so downstream string comparisons keep working;");
lines.push("// realmlib's name is exported below as an alias on PacketAlias.");
lines.push('export const PACKET_MAP: PacketMap = {');
for (const id of [...hiveMap.keys()].sort((a, b) => a - b)) {
  const { name: hiveName, comment } = hiveMap.get(id);
  const name = preferredName(hiveName);
  let line = `  "${id}": "${name}",`;
  if (comment) line += `  // ${comment}`;
  if (name !== hiveName) line += `${comment ? ' —' : '  //'} realmlib: ${hiveName}`;
  lines.push(line);
}
lines.push('};');
lines.push('');
lines.push('export const BIDIR_PACKET_MAP: PacketMap = invertPacketMap(PACKET_MAP);');
lines.push('');
lines.push('export enum PacketType {');
for (const name of primaryNames) lines.push(`  ${name} = "${name}",`);
lines.push('}');
lines.push('');
if (aliasPairs.length) {
  lines.push('/**');
  lines.push(' * Realmlib canonical names that differ from REC. Each alias resolves to the same');
  lines.push(' * wire string as the corresponding REC name, so `pkt.type === PacketAlias.VAULT_CONTENT`');
  lines.push(' * and `pkt.type === PacketType.VAULT_UPDATE` are both true.');
  lines.push(' */');
  lines.push('export const PacketAlias = {');
  for (const [hive, rec] of aliasPairs) lines.push(`  ${hive}: PacketType.${rec},`);
  lines.push('} as const;');
  lines.push('');
}
lines.push('// Direction is not encoded in the wire protocol. Existing values are preserved from');
lines.push('// the prior REC map; new entries added by this sync are heuristically seeded and');
lines.push('// marked "NEW — verify". Verify each before relying on it.');
lines.push('export const PACKET_DIRECTION: Record<PacketType, "Incoming" | "Outgoing"> = {');
for (const name of primaryNames) {
  const d = guessDir(name);
  const marker = priorDirs.has(name) ? '' : '  // NEW — verify';
  lines.push(`  ${name}: "${d}",${marker}`);
}
lines.push('};');
lines.push('');

writeFileSync(OUT_PATH, lines.join('\n'));
console.log(`Wrote ${OUT_PATH}`);
console.log(`  ${hiveMap.size} packet IDs · ${primaryNames.length} enum values · ${aliasPairs.length} aliases`);
